import { COMMIT, GENOME, PROJECT, REPO } from './ids';

/**
 * The KEYLIT capability catalogue.
 *
 * These are semantic capabilities, not files. `input.music.midi.scheduling` is
 * a gene; `src/midi/buffer.ts` is one anchor that currently implements it. The
 * separation is what lets the Quechua fork and the Swift rebuild be recognised
 * as carrying the same capability.
 */

type AlleleSeed = Omit<Allele, 'id'> & { id: Allele['id'] };

function gene(input: {
  local: string;
  name: string;
  description: string;
  term: string;
  tags: string[];
  originProject: string;
  originCommit: string;
  originDate: string;
  license?: string;
  semanticBoundary: number;
  originConfidence: number;
  alleles: AlleleSeed[];
  annotations?: Gene['annotations'];
  descendantProjects: number;
}): Gene {
  const alleles = input.alleles;
  const current = alleles[alleles.length - 1] as AlleleSeed;
  const carrierCount = new Set(alleles.flatMap((a) => a.carriedBy)).size;

  return {
    $schema: 'https://codeancestry.com/schemas/gene/v0.1.json',
    schemaVersion: '0.1',
    id: `CAGENE:${input.local}`,
    name: input.name,
    description: input.description,
    ontology: { term: input.term, tags: input.tags },
    currentAllele: current.id,
    alleles,
    origin: {
      project: input.originProject as Gene['origin']['project'],
      firstObservedCommit: input.originCommit,
      firstObservedAt: input.originDate,
    },
    license: { spdx: input.license ?? 'MIT' },
    annotations: input.annotations ?? [],
    confidence: {
      semanticBoundary: input.semanticBoundary,
      origin: input.originConfidence,
    },
    stats: {
      carrierCount,
      alleleCount: alleles.length,
      mutationCount: alleles.filter((a) => a.producedBy).length,
      descendantProjects: input.descendantProjects,
    },
  };
}

