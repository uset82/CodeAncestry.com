/**
 * The eight seeded genomes. Generation 0 through one three-parent hybrid.
 *
 * Track data (dependencies, security, agent activity, tests) is positioned on a
 * normalised 0–1 axis so the genome browser can lay it out under any of the
 * three coordinate modes without re-deriving anything.
 */

type GeneSeed = [
  local: string,
  allele: number,
  version: string,
  digest: string,
  inheritance: GenomeGeneRef['inheritance'],
  weight: number,
  confidence: number,
  evidence: string[],
  origin?: keyof typeof PROJECT,
];

function genes(seeds: GeneSeed[], repo: string, commit: string): GenomeGeneRef[] {
  return seeds.map(
    ([local, allele, version, digest, inheritance, weight, confidence, evidence, origin]) => ({
      gene: `CAGENE:${local}` as GenomeGeneRef['gene'],
      allele: `CAALLELE:${local}:${allele}` as GenomeGeneRef['allele'],
      version,
      digest: digest as GenomeGeneRef['digest'],
      expression: 'active' as const,
      inheritance,
      ...(origin ? { origin: PROJECT[origin] as GenomeGeneRef['origin'] } : {}),
      confidence,
      evidence: evidence as GenomeGeneRef['evidence'],
      anchors: [
        {
          repository: repo,
          commit,
          path: `src/${local.toLowerCase()}/index.ts`,
          symbols: [],
        },
      ],
      weight,
    }),
  );
}

